import Foundation
import Observation

struct Exercise: Codable, Identifiable, Hashable {
    let id: String
    let name: String
    let symbol: String
    let summary: String
    let cues: [String]
    /// Rough seconds per rep, used to estimate how long rep-based sets take.
    let secondsPerRep: Int
}

enum WorkoutCategory: String, Codable, CaseIterable, Identifiable {
    case programme, strength, conditioning, complexes, recovery

    var id: String { rawValue }

    var title: String {
        switch self {
        case .programme: "Beginner Programme"
        case .strength: "Strength"
        case .conditioning: "Conditioning"
        case .complexes: "Complexes"
        case .recovery: "Recovery"
        }
    }

    var symbol: String {
        switch self {
        case .programme: "figure.strengthtraining.functional"
        case .strength: "figure.strengthtraining.traditional"
        case .conditioning: "figure.highintensity.intervaltraining"
        case .complexes: "figure.cross.training"
        case .recovery: "figure.mind.and.body"
        }
    }
}

/// One exercise slot inside a block. Either timed (`work` seconds) or rep-based (tap Done).
struct WorkoutItem: Codable, Hashable {
    let exercise: String
    var work: Int?
    var reps: Int?
    let rest: Int
    /// Rep sets: done once per side. Timed: one interval per side.
    var perSide: Bool?
    /// Shown instead of a rep count, e.g. "Max good reps" or "10 swings → 5 goblet squats".
    var target: String?
    var note: String?
    /// Shows a "+1 round" counter (AMRAPs).
    var counter: Bool?

    var isTimed: Bool { work != nil }
}

struct WorkoutBlock: Codable, Hashable {
    let name: String
    let rounds: Int
    /// Replaces the last item's rest at the end of every round except the final one.
    var restBetweenRounds: Int?
    let items: [WorkoutItem]

    /// A single rep-based exercise repeated for several sets.
    var isStraightSets: Bool { items.count == 1 && !items[0].isTimed }
}

struct Workout: Codable, Identifiable, Hashable {
    let id: String
    let title: String
    let subtitle: String
    let category: WorkoutCategory
    let level: String
    let focus: String
    let theme: String
    let description: String
    let bells: Int
    /// Whether the shared warm-up and cool-down can be added.
    let warmup: Bool
    let blocks: [WorkoutBlock]

    /// Big letter for programme sessions ("A"), otherwise nil.
    var badge: String? {
        category == .programme ? title.split(separator: " ").last.map(String.init) : nil
    }

    var hasRepSets: Bool {
        blocks.contains { $0.items.contains { !$0.isTimed } }
    }
}

private struct LibraryFile: Codable {
    let exercises: [Exercise]
    let warmup: WorkoutBlock
    let cooldown: WorkoutBlock
    let workouts: [Workout]
}

/// The bundled exercise and workout library (generated by tools/build_library.py).
@Observable
final class WorkoutLibrary {
    let exercises: [String: Exercise]
    let workouts: [Workout]
    let warmup: WorkoutBlock
    let cooldown: WorkoutBlock

    init(bundle: Bundle = .main) {
        var file = LibraryFile(exercises: [], warmup: WorkoutBlock(name: "Warm-Up", rounds: 0, items: []),
                               cooldown: WorkoutBlock(name: "Cool-Down", rounds: 0, items: []), workouts: [])
        do {
            guard let url = bundle.url(forResource: "library", withExtension: "json") else {
                throw CocoaError(.fileNoSuchFile)
            }
            file = try JSONDecoder().decode(LibraryFile.self, from: Data(contentsOf: url))
        } catch {
            assertionFailure("Couldn't load library.json: \(error)")
        }
        exercises = Dictionary(file.exercises.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first })
        workouts = file.workouts
        warmup = file.warmup
        cooldown = file.cooldown
    }

    func exercise(_ id: String?) -> Exercise? {
        id.flatMap { exercises[$0] }
    }

    func workout(id: String) -> Workout? {
        workouts.first { $0.id == id }
    }

    func workouts(in category: WorkoutCategory) -> [Workout] {
        workouts.filter { $0.category == category }
    }

    /// Minutes using the user's warm-up and rest settings.
    func minutes(_ workout: Workout) -> Int {
        let defaults = UserDefaults.standard
        let includeWarmup = defaults.object(forKey: "includeWarmup") as? Bool ?? true
        let rest = defaults.object(forKey: "restBetweenSets") as? Int ?? 60
        return minutes(workout, options: StepOptions(includeWarmup: includeWarmup && workout.warmup, restBetweenSets: rest))
    }

    func minutes(_ workout: Workout, options: StepOptions) -> Int {
        Int((Double(workout.estimatedSeconds(using: self, options: options)) / 60).rounded())
    }

    // MARK: Suggestions

    /// The programme session after the most recently completed one (A → B → C → A).
    func nextProgrammeSession(history: [CompletedWorkout]) -> Workout? {
        let programme = workouts(in: .programme)
        guard let last = history.first(where: { entry in programme.contains { $0.id == entry.workoutID } }),
              let index = programme.firstIndex(where: { $0.id == last.workoutID }) else {
            return programme.first
        }
        return programme[(index + 1) % programme.count]
    }

    /// Workouts you haven't done for the longest time, preferring a different kind from your last one.
    /// Ties are shuffled by day so the picks change daily.
    func freshPicks(history: [CompletedWorkout], count: Int = 5) -> [Workout] {
        let lastDone = Dictionary(history.map { ($0.workoutID, $0.date) }, uniquingKeysWith: { max($0, $1) })
        let lastCategory = history.first.flatMap { workout(id: $0.workoutID)?.category }
        let day = Calendar.current.ordinality(of: .day, in: .era, for: .now) ?? 0

        func key(_ workout: Workout) -> (Date, Int, Int) {
            (lastDone[workout.id] ?? .distantPast,
             workout.category == lastCategory ? 1 : 0,
             stableHash("\(workout.id)-\(day)"))
        }
        return workouts
            .filter { $0.category != .programme }
            .sorted { key($0) < key($1) }
            .prefix(count)
            .map { $0 }
    }

    private func stableHash(_ string: String) -> Int {
        string.unicodeScalars.reduce(5381) { ($0 &* 33) &+ Int($1.value) } & 0x7FFF_FFFF
    }
}
